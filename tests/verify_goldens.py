failed = 0
passed = 0


def check(name, got):
    global passed, failed
    path = os.path.join(GOLDEN_DIR, f"{name}.golden")
    if not os.path.exists(path):
        print(f"  SKIP {name}: golden file not found")
        return
    with open(path, "rb") as f:
        expected = f.read()
    if got == expected:
        passed += 1
        print(f"  PASS {name} ({len(got)} bytes)")
    else:
        failed += 1
        print(f"  FAIL {name}: expected {len(expected)} bytes, got {len(got)}")
        # Show first difference
        for i, (e, g) in enumerate(zip(expected, got)):
            if e != g:
                ctx = max(0, i - 20)
                print(f"    first diff at byte {i}: expected {e:02x}, got {g:02x}")
                print(f"    expected[{ctx}:{i+20}]: {expected[ctx:i+20]!r}")
                print(f"    got[{ctx}:{i+20}]:      {got[ctx:i+20]!r}")
                break
        else:
            if len(expected) != len(got):
                shorter = min(len(expected), len(got))
                print(f"    all {shorter} bytes match, but lengths differ")


