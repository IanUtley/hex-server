def verify_objfmt_response_zeroprop():
    type_names = ["Test.ZeroPropsHeader", "System.Int32", "System.String"]
    buf = io.BytesIO()
    sizes = [0]
    def w(s): buf.write(s.encode("utf-8"))
    def s():  buf.write(b";")
    w(""); s(); w("00"); s(); w("0"); s(); w("2"); s()
    f1 = buf.tell(); sizes.append(0)
    w("A"); s(); w("1"); s(); w(str(type_names.index("System.Int32"))); s(); w("0"); s()
    w(hexlify(struct.pack("<i", 99)).decode("ascii")); s()
    sizes[-1] = buf.tell() - f1
    f2 = buf.tell(); sizes.append(0)
    w("B"); s(); w("2"); s(); w(str(type_names.index("System.String"))); s(); w("0"); s()
    enc = b"test"; w(str(len(enc))); s(); buf.write(enc)
    sizes[-1] = buf.tell() - f2
    sizes[0] = buf.tell()
    w(";".join(type_names)); buf.write(b"\n")
    for i, z in enumerate(sizes):
        if i > 0: w(";")
        w(str(z))
    check("encode_objfmt_response_zeroprop", buf.getvalue())


