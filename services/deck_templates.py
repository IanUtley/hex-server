"""Profile deck templates (mercenary decks and saved deck templates).

The client saves a ProfileDeckTemplate through the profile service's JSON
``Network+Request``: ``{"action": "pdecktsave", "Template": <base64
ProfileDeckTemplate.ToBytes()>, "DeckTemplateID": <0 for new>}``.  The
response envelope is decoded with ``EncData.Decode`` (ObjFmt, not JSON) and
must be a ``Game.Shared.Profile.SavedProfileDeckTemplate``.  Saved templates
are also sent at login as ``List<SavedProfileDeckTemplate>``.

Templates are stored relationally (``player_deck_templates`` and
``player_deck_template_cards``); the client's bytes are regenerated from the
columns by ``encode_template``.  The regenerated bytes carry the same data as
the saved ones but are not guaranteed byte-identical: card descriptors are
regrouped per card GUID, and extended data other than ``gboard`` and
``personality`` is not kept.
"""

import base64
import io
import json
import struct

from encoder import encode_objfmt_response

SAVED_TEMPLATE_TYPE = "Game.Shared.Profile.SavedProfileDeckTemplate"
ZERO_GUID = "00000000-0000-0000-0000-000000000000"

# Reckoning.Game.EEquipmentType (ProfileDeckTemplate.Equip keys).
EQUIPMENT_SLOTS = ("Head", "Chest", "Gloves", "Feet", "Weapon", "Trinket")
EXT_GAMEBOARD = "gboard"
EXT_PERSONALITY = "personality"
FLAG_NAMES = ("extended", "reserves", "foil")


# ── ProfileDeckTemplate bytes (FromBytes / ToBytes) ──────────────────

def _read_varint(data, pos):
    value, shift = 0, 0
    while pos < len(data):
        byte = data[pos]
        pos += 1
        value |= (byte & 0x7F) << shift
        if not byte & 0x80:
            break
        shift += 7
    return value, pos


def _read_guid(data, pos):
    """Read a .NET Guid.ToByteArray() (mixed-endian) GUID."""
    raw = data[pos:pos + 16]
    if len(raw) != 16:
        raise ValueError("truncated GUID")
    a, b, c = struct.unpack("<IHH", raw[:8])
    tail = raw[8:].hex()
    return f"{a:08x}-{b:04x}-{c:04x}-{tail[:4]}-{tail[4:]}", pos + 16


def _read_string(data, pos):
    """Read a BinaryWriter.Write(string) value (varint length + UTF-8)."""
    length, pos = _read_varint(data, pos)
    raw = data[pos:pos + length]
    if len(raw) != length:
        raise ValueError("truncated string")
    return raw.decode("utf-8"), pos + length


def decode_template(data):
    """Decode ProfileDeckTemplate.ToBytes(), mirroring FromBytes.

    Returns ``{"name", "champion_guid", "sleeve_guid", "equipment":
    {slot name: guid}, "cards": [{"guid", "count", "reserves", "extended",
    "foil", "gems": [int]}], "extended": {key: value}}``.
    """
    data = bytes(data or b"")
    name, pos = _read_string(data, 0)
    champion, pos = _read_guid(data, pos)
    sleeve, pos = _read_guid(data, pos)
    equipment = {}
    count, pos = _read_varint(data, pos)
    for _ in range(count):
        slot, pos = _read_varint(data, pos)
        guid, pos = _read_guid(data, pos)
        key = EQUIPMENT_SLOTS[slot] if slot < len(EQUIPMENT_SLOTS) else str(slot)
        equipment[key] = guid
    cards = []
    count, pos = _read_varint(data, pos)
    for _ in range(count):
        guid, pos = _read_guid(data, pos)
        copies, pos = _read_varint(data, pos)
        if pos + 3 > len(data):
            raise ValueError("truncated card descriptor")
        reserves, extended, foil = (bool(data[pos]), bool(data[pos + 1]),
                                    bool(data[pos + 2]))
        pos += 3
        gem_count, pos = _read_varint(data, pos)
        gems = []
        for _ in range(gem_count):
            gem, pos = _read_varint(data, pos)
            gems.append(gem)
        cards.append({"guid": guid, "count": copies, "reserves": reserves,
                      "extended": extended, "foil": foil, "gems": gems})
    extended_data = {}
    if pos < len(data):
        count, pos = _read_varint(data, pos)
        for _ in range(count):
            key, pos = _read_string(data, pos)
            value, pos = _read_string(data, pos)
            extended_data[key] = value
    return {"name": name, "champion_guid": champion, "sleeve_guid": sleeve,
            "equipment": equipment, "cards": cards, "extended": extended_data}


def encode_template(template):
    """Encode a ``decode_template``-shaped dict as ProfileDeckTemplate.ToBytes()."""
    from encoded_decks import write_csharp_string, write_guid, write_varint
    buf = io.BytesIO()
    write_csharp_string(buf, template.get("name") or "")
    write_guid(buf, template.get("champion_guid") or ZERO_GUID)
    write_guid(buf, template.get("sleeve_guid") or ZERO_GUID)
    equipped = []
    for key, guid in (template.get("equipment") or {}).items():
        if not guid or guid == ZERO_GUID:
            continue
        slot = (EQUIPMENT_SLOTS.index(key) if key in EQUIPMENT_SLOTS
                else int(key))
        equipped.append((slot, guid))
    write_varint(buf, len(equipped))
    for slot, guid in equipped:
        write_varint(buf, slot)
        write_guid(buf, guid)
    cards = template.get("cards") or []
    write_varint(buf, len(cards))
    for card in cards:
        write_guid(buf, card["guid"])
        write_varint(buf, int(card["count"]))
        buf.write(bytes([1 if card.get("reserves") else 0,
                         1 if card.get("extended") else 0,
                         1 if card.get("foil") else 0]))
        gems = card.get("gems") or []
        write_varint(buf, len(gems))
        for gem in gems:
            write_varint(buf, int(gem))
    extended_data = template.get("extended") or {}
    write_varint(buf, len(extended_data))
    for key, value in extended_data.items():
        write_csharp_string(buf, key)
        write_csharp_string(buf, value)
    return buf.getvalue()


def template_cards(data):
    """Return the main-deck card GUIDs of ProfileDeckTemplate bytes.

    Reserve (sideboard) cards are skipped; each card is repeated ``count``
    times.
    """
    return [card["guid"] for card in decode_template(data)["cards"]
            if not card["reserves"] for _ in range(card["count"])]


def template_name(data):
    """Return the deck name stored at the start of ProfileDeckTemplate bytes."""
    try:
        return _read_string(bytes(data), 0)[0]
    except (UnicodeDecodeError, IndexError, TypeError, ValueError):
        return ""


# ── Columns <-> decoded template ─────────────────────────────────────

def template_columns(template):
    """Split a decoded template into (columns dict, card rows).

    Card rows are ``(card_guid, quantity, gem_types_list_json, flags_json)``,
    one per card GUID in first-seen order.
    """
    extended_data = template.get("extended") or {}
    columns = {
        "name": template.get("name") or "",
        "champion_guid": template.get("champion_guid") or "",
        "sleeve_guid": template.get("sleeve_guid") or "",
        "gameboard_guid": extended_data.get(EXT_GAMEBOARD, ""),
        "personality": extended_data.get(EXT_PERSONALITY, ""),
        "equipment_json": json.dumps(template.get("equipment") or {},
                                     sort_keys=True),
    }
    copies = {}
    for card in template.get("cards") or []:
        flags = {name: bool(card.get(name)) for name in FLAG_NAMES}
        gems = [int(gem) for gem in card.get("gems") or []]
        copies.setdefault(str(card["guid"]).lower(), []).extend(
            [(flags, gems)] * max(0, int(card.get("count") or 0)))
    rows = []
    for guid, entries in copies.items():
        if not entries:
            continue
        gems = ([list(g) for _f, g in entries]
                if any(g for _f, g in entries) else [])
        flags = dict(entries[0][0])
        if any(f != entries[0][0] for f, _g in entries):
            flags["copies"] = [dict(f) for f, _g in entries]
        rows.append((guid, len(entries), json.dumps(gems),
                     json.dumps(flags, sort_keys=True)))
    return columns, rows


def template_from_columns(row):
    """Rebuild a decoded template from a ``db_profile_deck_template`` dict."""
    extended_data = {}
    if row.get("gameboard_guid"):
        extended_data[EXT_GAMEBOARD] = row["gameboard_guid"]
    if row.get("personality"):
        extended_data[EXT_PERSONALITY] = row["personality"]
    cards = []
    for card in row.get("cards") or []:
        quantity = int(card["quantity"] or 0)
        gems = json.loads(card["gem_types_list_json"] or "[]")
        flags = json.loads(card["flags_json"] or "{}")
        per_copy_flags = flags.get("copies") or [flags] * quantity
        descriptors = {}
        for index in range(quantity):
            copy_flags = (per_copy_flags[index] if index < len(per_copy_flags)
                          else flags)
            copy_gems = gems[index] if index < len(gems) else []
            key = (tuple(bool(copy_flags.get(n)) for n in FLAG_NAMES),
                   tuple(int(g) for g in copy_gems))
            descriptors[key] = descriptors.get(key, 0) + 1
        for (flag_values, copy_gems), count in descriptors.items():
            cards.append({"guid": card["card_guid"], "count": count,
                          **dict(zip(FLAG_NAMES, flag_values)),
                          "gems": list(copy_gems)})
    return {"name": row.get("name") or "",
            "champion_guid": row.get("champion_guid") or ZERO_GUID,
            "sleeve_guid": row.get("sleeve_guid") or ZERO_GUID,
            "equipment": json.loads(row.get("equipment_json") or "{}"),
            "cards": cards, "extended": extended_data}


def template_bytes(row):
    """ProfileDeckTemplate bytes regenerated from a stored template."""
    return encode_template(template_from_columns(row))


def main_deck_cards(row):
    """Main-deck card GUIDs of a stored template, one entry per copy."""
    out = []
    for card in template_from_columns(row)["cards"]:
        if not card["reserves"]:
            out.extend([card["guid"]] * card["count"])
    return out


# ── Storage ──────────────────────────────────────────────────────────

def save_template(db, user_id, template_id, data):
    """Decode and store a template (insert or update); return (id, name)."""
    from profile_db import db_save_profile_deck_template
    columns, card_rows = template_columns(decode_template(data))
    template_id = db_save_profile_deck_template(
        user_id, template_id, columns, card_rows, conn=db)
    return template_id, columns["name"]


def delete_template(db, user_id, template_id):
    from profile_db import db_delete_profile_deck_template
    db_delete_profile_deck_template(user_id, template_id, conn=db)


def list_templates(db, user_id):
    """Return ``[(id, name, regenerated bytes), ...]`` of a player's templates."""
    from profile_db import db_profile_deck_templates
    return [(row["id"], row["name"], template_bytes(row))
            for row in db_profile_deck_templates(user_id, conn=db)]


def get_template(db, user_id, template_id):
    """Return a stored template dict (columns plus ``cards``) or None."""
    from profile_db import db_profile_deck_template
    return db_profile_deck_template(user_id, template_id, conn=db)


def encode_saved_template(template_id, name, data):
    return encode_objfmt_response(
        [SAVED_TEMPLATE_TYPE, "System.UInt64", "System.String",
         "System.Boolean", "System.Byte[]"],
        [("Id", "ulong", int(template_id)), ("Name", "string", name),
         ("Comp", "bool", False), ("Data", "bytes", data)])


def encode_saved_template_list(templates):
    from services.mercenaries import ObjFmtListWriter
    elements = [[("Id", "ulong", tid), ("Name", "string", name),
                 ("Comp", "bool", False), ("Data", "bytes", data)]
                for tid, name, data in templates]
    return ObjFmtListWriter(SAVED_TEMPLATE_TYPE).encode(SAVED_TEMPLATE_TYPE, elements)


def handle_profile_action(db, user_id, env_json):
    """Handle pdecktsave/pdeckdel; return the response envelope or None."""
    action = env_json.get("action")
    if action == "pdecktsave":
        data = base64.b64decode(env_json.get("Template") or "")
        template_id, name = save_template(
            db, user_id, env_json.get("DeckTemplateID"), data)
        db.commit()
        return encode_saved_template(template_id, name, data)
    if action == "pdeckdel":
        delete_template(db, user_id, env_json.get("DeckTemplateID"))
        db.commit()
        return b"{}"
    return None
